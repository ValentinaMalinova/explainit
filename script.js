// Показва готов или AI отговор в блока с отговора.
function renderAnswer(title, text, steps = []) {
  answer.hidden = false;
  answerTitle.textContent = title;
  answerText.textContent = text;
  answerSteps.replaceChildren();

  steps.forEach((step) => {
    const li = document.createElement('li');
    li.textContent = step;
    answerSteps.appendChild(li);
  });

  answer.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

// Изпраща въпроса към /api/ask. Gemini API ключът остава
// защитен в Environment Variables на Vercel и не се показва в браузъра.
async function askAI(question) {
  const response = await fetch('/api/ask', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ question })
  });

  let data = null;
  try {
    data = await response.json();
  } catch (error) {
    // Отговорът не е JSON — ще покажем обща грешка.
  }

  if (!response.ok || !data || !data.text) {
    const message = data && data.error ? data.error : 'AI услугата не е достъпна в момента.';
    throw new Error(message);
  }

  return data;
}

// Пази от застъпване на отговори, ако потребителят зададе нов въпрос,
// докато AI още мисли за предишния.
let latestRequestId = 0;

async function showAnswer(question) {
  const cleanedQuestion = question.trim();

  if (!cleanedQuestion) return;

  // 1. Първо търсим в готовата библиотека — бързо и безплатно.
  const match = findBestExplanation(cleanedQuestion);

  if (match) {
    latestRequestId += 1;
    renderAnswer(match.title, match.text, match.steps);
    return;
  }

  // 2. Няма готов отговор — питаме AI.
  const requestId = ++latestRequestId;
  const askButton = $('#askButton');

  if (askButton) askButton.disabled = true;
  renderAnswer('Мисля…', 'ExplainIt подготвя обяснение за твоя въпрос.');

  try {
    const data = await askAI(cleanedQuestion);

    if (requestId !== latestRequestId) return;

    renderAnswer(data.title, data.text, Array.isArray(data.steps) ? data.steps : []);
  } catch (error) {
    if (requestId !== latestRequestId) return;

    renderAnswer(
      'Нещо се обърка',
      error.message || 'Не успях да получа отговор от AI. Опитай отново след малко.'
    );

    // Предлагаме няколко въпроса с готови отговори.
    const exampleQuestions = [
      'Как работи GPS?',
      'Защо небето е синьо?',
      'Как се образува дъгата?',
      'Как работи Wi-Fi?'
    ];

    exampleQuestions.forEach((questionText) => {
      const li = document.createElement('li');
      const button = document.createElement('button');

      button.type = 'button';
      button.className = 'answer-example';
      button.textContent = questionText;

      button.addEventListener('click', () => {
        questionInput.value = questionText;
        showAnswer(questionText);
      });

      li.appendChild(button);
      answerSteps.appendChild(li);
    });
  } finally {
    if (askButton) askButton.disabled = false;
  }
}


