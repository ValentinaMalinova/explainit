function renderSuggestions(value) {
  if (!suggestionBox) return;

  const query = normalize(value);
  suggestionBox.replaceChildren();

  if (!query) {
    suggestionBox.hidden = true;
    return;
  }

  const words = query
    .split(' ')
    .filter((word) => word.length >= 2);

  const matches = suggestedQuestions
    .map((item) => {
      const normalizedQuestion = normalize(item.question);
      let score = 0;

      if (normalizedQuestion.includes(query)) {
        score += 10;
      }

      words.forEach((word) => {
        if (normalizedQuestion.includes(word)) {
          score += word.length >= 4 ? 3 : 1;
        }
      });

      return { ...item, score };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5);

  if (matches.length === 0) {
    suggestionBox.hidden = true;
    return;
  }

  matches.forEach((item) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'question-suggestion';
    button.setAttribute('role', 'option');

    const title = document.createElement('span');
    title.textContent = item.question;

    const category = document.createElement('small');
    category.textContent = item.category;

    button.append(title, category);

    button.addEventListener('click', () => {
      questionInput.value = item.question;
      suggestionBox.hidden = true;
      showAnswer(item.question);
    });

    suggestionBox.appendChild(button);
  });

  suggestionBox.hidden = false;
}

