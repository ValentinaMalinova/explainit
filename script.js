function findBestExplanation(question) {
  const normalizedQuestion = normalize(question);

  if (!normalizedQuestion) {
    return null;
  }

  const questionWords = normalizedQuestion
    .split(' ')
    .filter(word => word.length > 1);

  let bestMatch = null;
  let bestScore = 0;

  for (const explanation of explanations) {
    let score = 0;

    for (const key of explanation.keys) {
      const normalizedKey = normalize(key);

      if (!normalizedKey) {
        continue;
      }

      // Точно съвпадение с ключова фраза
      if (normalizedQuestion.includes(normalizedKey)) {
        score += normalizedKey.includes(' ') ? 5 : 3;
        continue;
      }

      // Проверка дали отделните думи от ключовата фраза
      // присъстват във въпроса
      const keyWords = normalizedKey
        .split(' ')
        .filter(word => word.length > 1);

      if (keyWords.length > 1) {
        const matchedWords = keyWords.filter(keyWord =>
          questionWords.includes(keyWord)
        ).length;

        if (matchedWords === keyWords.length) {
          score += 3;
        } else if (matchedWords > 0) {
          score += matchedWords / keyWords.length;
        }
      } else if (keyWords.length === 1 &&
                 questionWords.includes(keyWords[0])) {
        score += 2;
      }
    }

    if (score > bestScore) {
      bestScore = score;
      bestMatch = explanation;
    }
  }

  // Не показваме произволен отговор при твърде слабо съвпадение
  return bestScore >= 2 ? bestMatch : null;
}


