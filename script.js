// Уеднаквява главни/малки букви и премахва излишните интервали.

function normalize(text) {
  return text
    .toLocaleLowerCase('bg-BG')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zа-яё0-9\s-]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}



